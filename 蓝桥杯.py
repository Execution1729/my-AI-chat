# 总结方法:进制转换
# 1.标准进制转换：除以目标进制，把余数记下来，商变成新的数，继续除，直到商为0，把记下来的余数倒过来拼在一起
# 如十进制100转二进制：100/2=50 余0 50/2=25 余0 25/2=12 余1 12/2=6 余0 6/2=3 余0 3/2=1 余1 1/2=0 余1  因此转换后就是 01100100
# 2.跳过特定数字：数字序列不能出现某个数字，则找剩余数字的个数，作为新的进制。
# 如：不能有0，则在拿到余数后，需要 remainder + 1 才行。不能有4，则如果余数>= 4,则需要 remainder + 1 才能跳过4。以上是九进制。
# 若不能用8和9，剩下0-7共八个数字，相当于八进制。
# 先看题目禁用了哪些数字，用 10 - 禁用个数 算出进制，取余数时若碰到禁用数字区间则+1或+2等进行偏移
# 3.反向进制：从右往左，每一位乘以基数的位数次方然后相加。
# 如二进制 1010 转 10进制：0->0 x 2^0 = 0  1->1 x 2^1 = 2  0->0 x 2^2 = 0  1->1 x 2^3 = 8  0+2+0+8 = 10 因此1010转十进制就是 10
